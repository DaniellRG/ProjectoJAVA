    private void abrirVentana(javax.swing.JInternalFrame ventana) {
        
        for (javax.swing.JInternalFrame abierta : jDesktopPane1.getAllFrames()) {
            if (abierta.getClass() == ventana.getClass()) {
                abierta.dispose();
            }
        }
        
        int posicion = jDesktopPane1.getAllFrames().length;
        ventana.setLocation(20 + (posicion % 6) * 30, 15 + (posicion % 6) * 30);
        jDesktopPane1.add(ventana);
        ventana.setVisible(true);
    }

